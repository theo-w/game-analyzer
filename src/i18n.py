# 支持的语言列表
SUPPORTED_LANGUAGES = [
    {'code': 'zh', 'name': '中文', 'flag': '🇨🇳'},
    {'code': 'en', 'name': 'English', 'flag': '🇺🇸'}
]


class I18nManager:
    """国际化管理器"""
    
    _instance = None
    _current_language = 'zh'
    _translations = TRANSLATIONS
    
    def __new__(cls):
        if cls._instance is None:
            cls._instance = super(I18nManager, cls).__new__(cls)
        return cls._instance
    
    def get_language(self) -> str:
        """获取当前语言"""
        return self._current_language
    
    def set_language(self, lang_code: str):
        """设置当前语言"""
        if lang_code in self._translations:
            self._current_language = lang_code
        else:
            self._current_language = 'zh'
    
    def translate(self, key: str, **kwargs) -> str:
        """翻译字符串"""
        translations = self._translations.get(self._current_language, self._translations['zh'])
        text = translations.get(key, key)
        
        # 替换占位符
        if kwargs:
            text = text.format(**kwargs)
        
        return text
    
    def t(self, key: str, **kwargs) -> str:
        """简写翻译方法"""
        return self.translate(key, **kwargs)
    
    def get_supported_languages(self) -> List[Dict]:
        """获取支持的语言列表"""
        return SUPPORTED_LANGUAGES
    
    def load_translations(self, lang_code: str, translations: Dict):
        """加载自定义翻译"""
        if lang_code in self._translations:
            self._translations[lang_code] = {**self._translations[lang_code], **translations}
        else:
            self._translations[lang_code] = translations
    
    def export_translations(self, lang_code: str) -> Dict:
        """导出翻译字典"""
        return self._translations.get(lang_code, {})


# 全局实例
i18n = I18nManager()


def get_i18n() -> I18nManager:
    """获取国际化管理器"""
    return i18n


def _(key: str, **kwargs) -> str:
    """全局翻译函数"""
    return i18n.t(key, **kwargs)
